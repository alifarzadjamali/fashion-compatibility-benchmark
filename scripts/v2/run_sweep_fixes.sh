#!/usr/bin/env bash
# Post-run sweep (2026-11-24, deviations D4-D6): analyses the protocol pre-registered but
# Phase 2 did not run, plus one bug-fix rerun. Reads the frozen Phase 2 predictions; writes
# only to new directories (nothing in results/, results_r20k/ or a100_summary/ is touched).
#   user-only       IQON/POG user-only bootstrap sensitivity (protocol: sensitivity user_only),
#                   20,000 replicates as the main Holm p-values (D3)
#   a100-r20k       A100 summary at 20,000 replicates (same Holm floor issue as D3)
#   cseeds-eqfix    construction-seed sensitivity with the near-duplicate groups (D4 bug fix);
#                   probe predictions are reused (questions are regenerated byte-identically)
set -uo pipefail
cd "$(dirname "$0")/../.."
step=${1:?step}
freeze=configs/v2_protocol_hash.json
export OMP_NUM_THREADS=2 MKL_NUM_THREADS=2 OPENBLAS_NUM_THREADS=2 PYTHONHASHSEED=20260912
R=${REPBENCH_DATA_ROOT:-/data/$USER/repbench/data}; F=$R/v2/full; PY=.venv/bin/python
EQ="--equivalence polyvore_v2_clean=$R/v2/image_equivalence/polyvore/equivalence_groups.json \
 iqon3000_v2_clean=$R/v2/image_equivalence/iqon/equivalence_groups.json pog_v2_clean=$R/v2/image_equivalence/pog/equivalence_groups.json"
models=resnet50,fashionclip2,openclip_b32_laion2b,marqo_fashionclip,marqo_fashionsiglip,siglip_b16_224,siglip2_b16_384,dinov3_vitl16,gr_lite,dinov3_vitl16_336,clip_vitl14_336,pe_core_l14_336,siglip2_so400m_384,qwen3_vl_emb_2b,qwen3_vl_emb_8b
echo "=== $step start $(date '+%F %T')"
case $step in
  user-only)
    O=$F/results_useronly_r20k; mkdir -p $O
    [ -e $O/predictions ] || ln -s $F/results/predictions $O/predictions
    [ -f $O/manifest.json ] || cp $F/results/manifest.json $O/manifest.json
    $PY scripts/v2/pipeline.py --stage stats \
      --datasets "iqon3000_v2_clean=$R/v2/iqon3000_v2_clean/build_a=user,pog_v2_clean=$R/v2/pog_v2_clean/build_a=user" \
      --models $models --embeddings $F/emb --results $O --eval-split test --frozen-protocol-hash $freeze \
      --replicates 20000 $EQ ;;
  a100-r20k)
    $PY scripts/v2/a100_v2.py summarize --a100 $R/v2/a100_v2 --scores $F/a100_scores --output $F/a100_summary_r20k \
      --mllm $F/mllm/a100_lat $F/mllm/a100_aat --replicates 20000 ;;
  cseeds-eqfix)
    O=$F/sens_eqfix; mkdir -p $O/construction_seeds
    [ -d $O/construction_seeds/predictions ] || cp -a $F/results/sensitivities/construction_seeds/predictions $O/construction_seeds/
    $PY scripts/v2/run_sensitivities.py construction-seeds --out $O --results $F/results --eval-split test \
      --frozen-protocol-hash $freeze --dataset-config configs/v2_sensitivity_datasets.json \
      --embeddings $F/emb --selection-split valid $EQ
    # the regenerated questions must be byte-identical to the Phase 2 ones (predictions reused)
    for d in $O/construction_seeds/protocols/*/seed_*; do
      rel=${d#$O/construction_seeds/}
      for f in compatibility_test.txt fill_in_blank_test.json; do
        cmp -s $d/$f $F/results/sensitivities/construction_seeds/$rel/$f || echo "MISMATCH $rel/$f"
      done
    done ;;
  *) echo "unknown step $step"; exit 2 ;;
esac
rc=$?; echo "=== $step end rc=$rc $(date '+%F %T')"
