"""Generate LaTeX tables, number macros and figures from pipeline CSVs (no hand-typing).

Inputs (written by scripts/v2/pipeline.py): `<results>/metrics.csv` with columns
dataset, model, setting, learner, split, metric, value, ci_low, ci_high; optional
`<results>/pairwise.csv` and `<results>/rank_intervals.csv`.
Outputs in `<out>`: `table_main.tex`, `table_settings.tex`, `numbers.tex`
(`\\newcommand` macros, one per metric value), `numbers.json` (the same values,
for scripts/v2/check_paper_numbers.py) and `fig_cp_auc.pdf`.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

import pandas as pd


def macro_name(*parts):
    words = []
    for part in parts:
        for token in re.split(r"[^A-Za-z0-9]+", str(part)):
            if token:
                digits = "Zero One Two Three Four Five Six Seven Eight Nine".split()
                token = re.sub(r"\d", lambda m: digits[int(m.group())], token)
                words.append(token[0].upper() + token[1:])
    return "res" + "".join(words)


def fmt(metric, value):
    return f"{value:.3f}" if metric.endswith("auc") else f"{100 * value:.1f}"


def table(frame, index, columns, caption, label):
    pivot = frame.pivot_table(index=index, columns=columns, values="cell", aggfunc="first")
    lines = [
        "\\begin{table}[t]\\centering\\small",
        f"\\caption{{{caption}}}\\label{{{label}}}",
        "\\begin{tabular}{l" + "c" * len(pivot.columns) + "}\\toprule",
        " & ".join([index.replace("_", " ")] + [str(c).replace("_", "\\_") for c in pivot.columns])
        + " \\\\\\midrule",
    ]
    for key, row in pivot.iterrows():
        cells = ["--" if pd.isna(v) else v for v in row]
        lines.append(" & ".join([str(key).replace("_", "\\_")] + cells) + " \\\\")
    lines += ["\\bottomrule\\end{tabular}", "\\end{table}"]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--results", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--primary-setting", default="native")
    parser.add_argument("--primary-learner", default="logistic")
    args = parser.parse_args()
    metrics = pd.read_csv(args.results / "metrics.csv")
    required = {"dataset", "model", "setting", "learner", "split", "metric", "value"}
    if missing := required - set(metrics.columns):
        raise ValueError(f"metrics.csv lacks {sorted(missing)}")
    args.out.mkdir(parents=True, exist_ok=True)
    metrics["cell"] = [
        fmt(m, v) + (f" [{fmt(m, lo)}, {fmt(m, hi)}]" if pd.notna(lo) and pd.notna(hi) else "")
        for m, v, lo, hi in zip(
            metrics.metric, metrics.value,
            metrics.get("ci_low", pd.Series([None] * len(metrics))),
            metrics.get("ci_high", pd.Series([None] * len(metrics))),
            strict=True,
        )
    ]
    primary = metrics[
        (metrics.setting == args.primary_setting) & (metrics.learner == args.primary_learner)
    ].copy()
    primary["column"] = primary.dataset + " " + primary.metric
    (args.out / "table_main.tex").write_text(
        table(primary, "model", "column", "Primary setting (native features, logistic probe). "
              "Generated by scripts/v2/make_tables_v2.py.", "tab:v2-main")
    )
    settings = metrics[metrics.metric == "cp_auc"].copy()
    settings["column"] = settings.setting + "/" + settings.learner
    settings["row"] = settings.dataset + ": " + settings.model
    (args.out / "table_settings.tex").write_text(
        table(settings, "row", "column", "CP AUC across feature settings and learners.",
              "tab:v2-settings")
    )
    numbers = {}
    for row in metrics.itertuples():
        name = macro_name(row.dataset, row.model, row.setting, row.learner, row.split, row.metric)
        if name in numbers:
            raise ValueError(f"Duplicate macro {name}")
        numbers[name] = fmt(row.metric, row.value)
    (args.out / "numbers.tex").write_text(
        "% Generated; do not edit.\n"
        + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in sorted(numbers.items()))
    )
    (args.out / "numbers.json").write_text(json.dumps(numbers, indent=1, sort_keys=True))
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    cp = primary[primary.metric == "cp_auc"]
    if len(cp):
        fig, ax = plt.subplots(figsize=(6, 0.4 * cp.model.nunique() + 1.5))
        palette = ["#0072B2", "#E69F00", "#009E73", "#CC79A7", "#56B4E9"]  # colour-blind safe
        for i, (dataset, group) in enumerate(cp.groupby("dataset")):
            group = group.sort_values("model")
            y = [sorted(cp.model.unique()).index(m) + 0.15 * i for m in group.model]
            err = None
            if "ci_low" in group and group.ci_low.notna().all():
                err = [group.value - group.ci_low, group.ci_high - group.value]
            ax.errorbar(group.value, y, xerr=err, fmt="o", color=palette[i % 5], label=dataset)
        ax.set_yticks(range(cp.model.nunique()), sorted(cp.model.unique()))
        ax.set_xlabel("CP AUC (primary setting)")
        ax.legend(frameon=False, fontsize=8)
        fig.tight_layout()
        fig.savefig(args.out / "fig_cp_auc.pdf")
    print(f"{len(numbers)} macros, tables and figure written to {args.out}")


if __name__ == "__main__":
    main()
